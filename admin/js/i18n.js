// Default to Japanese on first landing (no saved preference yet); a returning
// user's explicit EN/日本語 choice is remembered in localStorage and wins.
let _lang = localStorage.getItem("admin_lang") || "ja";
const _listeners = [];

export function getLang() {
  return _lang;
}

export function setLang(lang) {
  if (lang !== "en" && lang !== "ja") return;
  _lang = lang;
  localStorage.setItem("admin_lang", lang);
  document.documentElement.lang = lang;
  applyStaticI18n();
  _listeners.forEach((fn) => fn(lang));
}

/** Register a callback fired whenever the language changes. */
export function onLangChange(fn) {
  _listeners.push(fn);
}

/** Translate a key, interpolating {placeholders} from `vars`. */
export function t(key, vars) {
  let s = (STRINGS[_lang] && STRINGS[_lang][key]) || STRINGS.en[key] || key;
  if (vars) {
    for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  }
  return s;
}

/** Apply translations to all [data-i18n], [data-i18n-ph], [data-i18n-html]. */
export function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPh));
  });
}
